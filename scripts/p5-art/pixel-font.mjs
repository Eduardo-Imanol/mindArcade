export function glyphFor(char) {
  return G[String(char).toUpperCase()] ?? G['?'];
}

export function textWidth(text, scale = 1) {
  const chars = String(text).length;
  if (chars === 0) return 0;
  return (chars * (GLYPH_WIDTH + GLYPH_SPACING) - GLYPH_SPACING) * scale;
}

export function drawText(canvas, text, x, y, { scale = 1, color = '#ffffff' } = {}) {
  const chars = String(text).toUpperCase().split('');
  let cursor = x;
  for (const char of chars) {
    const glyph = glyphFor(char);
    for (let row = 0; row < GLYPH_HEIGHT; row += 1) {
      for (let col = 0; col < GLYPH_WIDTH; col += 1) {
        if (glyph[row][col] !== '#') continue;
        fillRect(canvas, cursor + col * scale, y + row * scale, scale, scale, color);
      }
    }
    cursor += (GLYPH_WIDTH + GLYPH_SPACING) * scale;
  }
  return cursor - x;
}
